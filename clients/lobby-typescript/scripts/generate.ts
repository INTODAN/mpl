#!/usr/bin/env bun
/**
 * Generates the player API's types from the checked-in OpenAPI document,
 * api/openapi.json, into src/generated/openapi.ts. With --check, it compares
 * them with the file and changes nothing.
 *
 * The API documents themselves come from Go: run the exporter first (README,
 * "Commands"). Never edit src/generated/ by hand.
 */
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const source = new URL("../../../api/openapi.json", import.meta.url);
const destination = new URL("../src/generated/openapi.ts", import.meta.url);

const header = `// Generated by scripts/generate.ts from api/openapi.json. Do not edit.
// Regenerate: bun run generate (in clients/lobby-typescript).

`;

const ast = await openapiTS(source, { alphabetize: true });
const generated = header + astToString(ast);

if (process.argv.includes("--check")) {
	const current = await readFile(destination, "utf8").catch(() => "");
	if (current !== generated) {
		console.error(
			"src/generated/openapi.ts is not current with api/openapi.json; run: bun run generate",
		);
		process.exit(1);
	}
} else {
	await writeFile(destination, generated);
}
